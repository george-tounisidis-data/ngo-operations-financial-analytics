-- 1. dbo.vw_Payroll_Anonymized
-- Φιλτράρει και απομονώνει τις δαπάνες προσωπικού, εφαρμόζοντας Data Masking.
-- =========================================================================
CREATE OR ALTER VIEW dbo.vw_Payroll_Anonymized AS
SELECT 
   -- Ανωνυμοποίηση Έργου (π.χ. Έργο 1, Έργο 2)
   N'Έργο ' + CAST(DENSE_RANK() OVER (ORDER BY [Έργο]) AS NVARCHAR(10)) AS [Πρόγραμμα/Έργο],
   
   -- Ανωνυμοποίηση Εργαζόμενης (π.χ. Εργαζόμενος 1, Εργαζόμενος 2)
   N'Εργαζόμενος ' + CAST(DENSE_RANK() OVER (ORDER BY [Επωνυμία/Ονοματεπώνυμο]) AS NVARCHAR(10)) AS [Εργαζόμενη],
   
   MONTH([Ημ/νία]) AS [Μήνας], 
   
   -- Τα οικονομικά ποσά παραμένουν ατόφια
   SUM([Συνολική αξία ]) AS [Συνολικό Ποσό Χρέωσης],
   
   COUNT(*) AS [Πλήθος Παραστατικών]
FROM dbo.EBS
WHERE [Έργο] IS NOT NULL 
  AND [Επωνυμία/Ονοματεπώνυμο] IS NOT NULL
  -- Φίλτρα Εταιρειών & Σταθερών Δαπανών
  AND [Επωνυμία/Ονοματεπώνυμο] NOT LIKE N'%ΕΝΟΙΚΙΟ%'
  AND [Επωνυμία/Ονοματεπώνυμο] NOT LIKE N'%ΕΝΟΙΚΙΑ%'
