-- =========================================================================
-- 2. dbo.vw_Expenses_Anonymized
-- Ομαδοποιεί τα λειτουργικά έξοδα και επιμερίζει ισομερώς τις κοινές δαπάνες.
-- =========================================================================
CREATE OR ALTER VIEW dbo.vw_Expenses_Anonymized AS
WITH RawExpenses AS (
    SELECT 
        CASE 
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 1%' THEN N'Γραφείο 1'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 2%' THEN N'Γραφείο 2'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 3%' THEN N'Γραφείο 2'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 4%' THEN N'Γραφείο 3'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΚΕΝΤΡΙΚΟ%' THEN N'Γραφείο 4'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 5%' THEN N'Γραφείο 4'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 6%' THEN N'Γραφείο 4'
            ELSE N'Γραφείο 4'
        END AS [Παράρτημα/Γραφείο],
        CASE 
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΟ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΑ%' THEN N'Ενοίκια'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΚΟΙΝΟΧΡΗΣΤΑ%' THEN N'Κοινόχρηστα'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΔΕΗ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΑΕΡΙΟ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΥΔΑΠ%' THEN N'Ενέργεια & Κοινή Ωφέλεια'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΟΤΕ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%COSMOTE%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VODAFONE%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%WIND%' THEN N'Τηλεπικοινωνίες'
            ELSE N'Λοιπά Λειτουργικά'
        END AS [Κατηγορία Εξόδου],
        MONTH([Ημ/νία]) AS [Μήνας],
        SUM([Συνολική αξία ]) AS [Συνολικό Κόστος]
    FROM dbo.EBS
    WHERE 
        ([Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΟ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΑ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΚΟΙΝΟΧΡΗΣΤΑ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΔΕΗ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΑΕΡΙΟ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΥΔΑΠ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΟΤΕ%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%COSMOTE%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VODAFONE%'
        OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%WIND%')
        AND [Επωνυμία/Ονοματεπώνυμο] NOT LIKE N'%VOICELAND%'
    GROUP BY 
        CASE 
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 1%' THEN N'Γραφείο 1'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 2%' THEN N'Γραφείο 2'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 3%' THEN N'Γραφείο 2'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 4%' THEN N'Γραφείο 3'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΚΕΝΤΡΙΚΟ%' THEN N'Γραφείο 4'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 5%' THEN N'Γραφείο 4'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%Διεύθυνση 6%' THEN N'Γραφείο 4'
            ELSE N'Γραφείο 4'
        END,
        CASE 
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΟ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΝΟΙΚΙΑ%' THEN N'Ενοίκια'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΚΟΙΝΟΧΡΗΣΤΑ%' THEN N'Κοινόχρηστα'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΔΕΗ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΑΕΡΙΟ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΕΥΔΑΠ%' THEN N'Ενέργεια & Κοινή Ωφέλεια'
            WHEN [Επωνυμία/Ονοματεπώνυμο] LIKE N'%ΟΤΕ%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%COSMOTE%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VODAFONE%' OR [Επωνυμία/Ονοματεπώνυμο] LIKE N'%WIND%' THEN N'Τηλεπικοινωνίες'
            ELSE N'Λοιπά Λειτουργικά'
        END,
        MONTH([Ημ/νία])

    UNION ALL

    -- Advanced Cost Allocation Logic: Ισομερής επιμερισμός της Voiceland στα 4 γραφεία
    SELECT N'Γραφείο 4' AS [Παράρτημα/Γραφείο], N'Τηλεπικοινωνίες' AS [Κατηγορία Εξόδου], MONTH([Ημ/νία]) AS [Μήνας], SUM([Συνολική αξία ]) / 4.0 AS [Συνολικό Κόστος] FROM dbo.EBS WHERE [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VOICELAND%' GROUP BY MONTH([Ημ/νία])
    UNION ALL
    SELECT N'Γραφείο 1' AS [Παράρτημα/Γραφείο], N'Τηλεπικοινωνίες' AS [Κατηγορία Εξόδου], MONTH([Ημ/νία]) AS [Μήνας], SUM([Συνολική αξία ]) / 4.0 AS [Συνολικό Κόστος] FROM dbo.EBS WHERE [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VOICELAND%' GROUP BY MONTH([Ημ/νία])
    UNION ALL
    SELECT N'Γραφείο 2' AS [Παράρτημα/Γραφείο], N'Τηλεπικοινωνίες' AS [Κατηγορία Εξόδου], MONTH([Ημ/νία]) AS [Μήνας], SUM([Συνολική αξία ]) / 4.0 AS [Συνολικό Κόστος] FROM dbo.EBS WHERE [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VOICELAND%' GROUP BY MONTH([Ημ/νία])
    UNION ALL
    SELECT N'Γραφείο 3' AS [Παράρτημα/Γραφείο], N'Τηλεπικοινωνίες' AS [Κατηγορία Εξόδου], MONTH([Ημ/νία]) AS [Μήνας], SUM([Συνολική αξία ]) / 4.0 AS [Συνολικό Κόστος] FROM dbo.EBS WHERE [Επωνυμία/Ονοματεπώνυμο] LIKE N'%VOICELAND%' GROUP BY MONTH([Ημ/νία])
)
-- Τελικό Select με Group By για την αποφυγή διπλότυπων γραμμών από το UNION ALL
SELECT 
    [Παράρτημα/Γραφείο],
    [Κατηγορία Εξόδου],
    [Μήνας],
    SUM([Συνολικό Κόστος]) AS [Συνολικό Κόστος]
FROM RawExpenses
GROUP BY [Παράρτημα/Γραφείο], [Κατηγορία Εξόδου], [Μήνας];
GO
